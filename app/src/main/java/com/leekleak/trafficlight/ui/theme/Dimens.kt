package com.leekleak.trafficlight.ui.theme

import androidx.compose.ui.unit.dp

/**
 * A single, predictable spacing scale for the whole app.
 *
 * Every gap/padding value in redesigned screens should come from here instead of a
 * one-off `Xdp` literal, so spacing stays visually consistent across screens.
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp
}
